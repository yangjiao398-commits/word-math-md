def set_font(run, size=11, bold=False, color=None):
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.name = "微软雅黑"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "微软雅黑")
    if color:
        run.font.color.rgb = RGBColor(*color)


def heading(doc, text, level):
    p = doc.add_heading(text, level=level)
    size = {1: 16, 2: 14, 3: 12}.get(level, 12)
    for run in p.runs:
        set_font(run, size, True, (31, 78, 121))


def para(doc, text, *, bold=False, size=11):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(6)
    p.paragraph_format.line_spacing = 1.15
    set_font(p.add_run(text), size, bold)
    return p


def bullets(doc, items):
    for item in items:
        p = doc.add_paragraph(style="List Bullet")
        p.paragraph_format.space_after = Pt(2)
        if p.runs:
            p.runs[0].text = ""
        set_font(p.add_run(item), 11)


def shade(row):
    for cell in row.cells:
        for p in cell.paragraphs:
            for run in p.runs:
                run.font.bold = True
                run.font.size = Pt(10)
                run.font.color.rgb = RGBColor(255, 255, 255)
                run.font.name = "微软雅黑"
                run._element.rPr.rFonts.set(qn("w:eastAsia"), "微软雅黑")
        tc_pr = cell._tc.get_or_add_tcPr()
        tc_pr.append(
            tc_pr.makeelement(
                qn("w:shd"), {qn("w:fill"): "1F4E79", qn("w:val"): "clear"}
            )
        )


def table(doc, headers, rows):
    t = doc.add_table(rows=1 + len(rows), cols=len(headers))
    t.style = "Table Grid"
    for i, header in enumerate(headers):
        t.rows[0].cells[i].text = header
    shade(t.rows[0])
    for r, row in enumerate(rows, 1):
        for c, value in enumerate(row):
            t.rows[r].cells[c].text = value
            for p in t.rows[r].cells[c].paragraphs:
                for run in p.runs:
                    set_font(run, 9)
    doc.add_paragraph()
    return t


